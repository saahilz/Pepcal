"use client";

/**
 * /export/print — a printable clinical summary for a doctor or telehealth
 * visit. One page, print-to-PDF ready, with the CSV twin beside it.
 *
 * Like everything here: record-keeping, repackaged. It shows what was logged,
 * and states its own provenance — "Patient-reported self-monitoring record."
 *
 * Names appear exactly as entered, on purpose: Discretion mode is a
 * shoulder-surfing display setting for browsing, and a sheet handed to a
 * clinician is the opposite of that. The CSV is generated in the browser from
 * the already-loaded records; nothing is sent anywhere.
 */

import { useMemo } from "react";
import Link from "next/link";
import { useData } from "@/components/app-provider";
import { useToast } from "@/components/toast-provider";
import { Button, Card, EmptyState } from "@/components/ui";
import { DownloadIcon } from "@/components/icons";
import { buildMedicalLogCsv, summarizeExports } from "@/lib/domain/export";
import { weightDeltaLabel, weightLabel } from "@/lib/domain/weight";
import { U100_UNITS_PER_ML } from "@/lib/domain/syringe";
import { amountLabel, formatDate, formatTime, trimNumber } from "@/lib/format";
import type { WeightEntry } from "@/lib/data/types";

/** Last reading recorded at or before `iso` (viewer-local comparison is fine
 *  for "around the dose" — both are instants). */
function atOrBefore(weights: WeightEntry[], iso: string): WeightEntry | null {
  let best: WeightEntry | null = null;
  for (const w of weights) {
    if (w.recordedAt <= iso && (best === null || w.recordedAt > best.recordedAt)) best = w;
  }
  return best;
}

export default function ExportPrintPage() {
  const { injections, vials, weights } = useData();
  const { show } = useToast();

  const summary = useMemo(() => summarizeExports(injections, weights), [injections, weights]);
  const rows = useMemo(
    () =>
      [...injections]
        .sort((a, b) => b.administeredAt.localeCompare(a.administeredAt))
        .map((i) => ({
          i,
          vial: i.vialId ? vials.find((v) => v.id === i.vialId) : undefined,
        })),
    [injections, vials]
  );

  function downloadCsv() {
    try {
      const csv = buildMedicalLogCsv({ injections, vials, weights });
      const url = URL.createObjectURL(new Blob([csv], { type: "text/csv;charset=utf-8" }));
      const a = document.createElement("a");
      a.href = url;
      a.download = `pepcal-medical-log-${new Date().toISOString().slice(0, 10)}.csv`;
      a.click();
      URL.revokeObjectURL(url);
    } catch (err) {
      show(err instanceof Error ? err.message : "Could not build the CSV.");
    }
  }

  if (rows.length === 0) {
    return (
      <div className="mx-auto max-w-2xl">
        <EmptyState
          emoji="🧾"
          title="Nothing to export yet"
          body="This sheet builds itself from your injection log — record an injection and it appears here."
          action={
            <Link href="/log">
              <Button>Log an injection</Button>
            </Link>
          }
        />
      </div>
    );
  }

  const firstW = summary.from ? atOrBefore(weights, summary.from) : null;
  const lastW = summary.to ? atOrBefore(weights, summary.to) : null;

  return (
    <div className="mx-auto flex max-w-3xl flex-col gap-4">
      <div className="flex flex-wrap items-end justify-between gap-3 print:hidden">
        <div>
          <h1 className="text-2xl font-semibold tracking-tight">Doctor summary</h1>
          <p className="mt-1 text-sm text-muted">
            A printable page of everything logged. Names show as entered — discretion
            does not apply to a clinical record, on purpose.
          </p>
        </div>
        <div className="flex gap-2">
          <Button variant="secondary" onClick={downloadCsv}>
            <DownloadIcon className="h-4.5 w-4.5" /> CSV
          </Button>
          <Button onClick={() => window.print()}>Print / Save as PDF</Button>
        </div>
      </div>

      <Card className="p-5 sm:p-7 print-sheet">
        <header className="border-b border-line pb-3">
          <h2 className="text-lg font-semibold tracking-tight">Injection &amp; weight log</h2>
          <p className="mt-0.5 text-sm font-medium">Patient-reported self-monitoring record.</p>
          <p className="mt-1 text-xs text-subtle">
            Prepared {formatDate(new Date().toISOString())} · generated by Pepcal from the
            entries shown below · {rows.length} dose{rows.length === 1 ? "" : "s"}
          </p>
        </header>

        <dl className="mt-4 grid grid-cols-2 gap-x-6 gap-y-3 text-sm sm:grid-cols-4">
          <Cell label="Date range">
            {formatDate(summary.from!)} – {formatDate(summary.to!)}
          </Cell>
          <Cell label="Total doses">{rows.length}</Cell>
          <Cell label="Average interval">
            {summary.avgDaysBetween === null
              ? "single dose"
              : `every ${trimNumber(summary.avgDaysBetween, 1)} days`}
          </Cell>
          <Cell label="Weight change over span">
            {firstW && lastW && firstW.id !== lastW.id
              ? `${weightDeltaLabel(lastW.weightKg - firstW.weightKg, "kg")} (${weightLabel(
                  firstW.weightKg,
                  "kg"
                )} → ${weightLabel(lastW.weightKg, "kg")})`
              : "not enough readings"}
          </Cell>
        </dl>
        <p className="mt-2 text-xs text-subtle">
          Weight change compares the last reading at or before the first dose with the last
          reading at or before the final dose.
        </p>

        <div className="mt-5 overflow-x-auto">
          <table className="w-full text-sm">
            <caption className="sr-only">
              Every logged injection, newest first: when, what, how much drawn, where, weight
              that day, and notes.
            </caption>
            <thead>
              <tr className="border-y border-line text-left text-xs uppercase tracking-wide text-subtle">
                <th scope="col" className="py-2 pr-3 font-medium">When</th>
                <th scope="col" className="py-2 pr-3 font-medium">Compound / vial</th>
                <th scope="col" className="py-2 pr-3 text-right font-medium">Dose</th>
                <th scope="col" className="py-2 pr-3 text-right font-medium">Draw</th>
                <th scope="col" className="py-2 pr-3 font-medium">Site</th>
                <th scope="col" className="py-2 pr-3 text-right font-medium">Weight</th>
                <th scope="col" className="py-2 font-medium">Notes</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-line align-top">
              {rows.map(({ i, vial }) => {
                const volMl =
                  i.volumeMl ??
                  (i.concentrationMcgPerMl != null && i.concentrationMcgPerMl > 0
                    ? (i.amountUnit === "mg" ? i.amount * 1000 : i.amount) / i.concentrationMcgPerMl
                    : null);
                const dayWeight = atOrBefore(weights, i.administeredAt);
                return (
                  <tr key={i.id}>
                    <td className="whitespace-nowrap py-2 pr-3 tabular-nums">
                      {formatDate(i.administeredAt)}
                      <span className="block text-xs text-subtle">
                        {formatTime(i.administeredAt)}
                      </span>
                    </td>
                    <td className="py-2 pr-3">
                      {i.vialNameSnapshot ?? vial?.name ?? "—"}
                      {vial?.notes ? (
                        <span className="block max-w-[14rem] truncate text-xs text-subtle">
                          {vial.notes}
                        </span>
                      ) : null}
                    </td>
                    <td className="whitespace-nowrap py-2 pr-3 text-right tabular-nums">
                      {amountLabel(i.amount, i.amountUnit)}
                    </td>
                    <td className="whitespace-nowrap py-2 pr-3 text-right tabular-nums">
                      {volMl !== null ? `${trimNumber(volMl, 3)} mL` : "—"}
                      {volMl !== null ? (
                        <span className="block text-xs text-subtle">
                          {trimNumber(volMl * U100_UNITS_PER_ML, 1)} U
                        </span>
                      ) : null}
                    </td>
                    <td className="py-2 pr-3">{i.location?.label ?? "—"}</td>
                    <td className="whitespace-nowrap py-2 pr-3 text-right tabular-nums">
                      {dayWeight ? weightLabel(dayWeight.weightKg, "kg") : "—"}
                    </td>
                    <td className="py-2 text-muted">{i.notes ?? ""}</td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>

        <p className="mt-4 rounded-xl bg-surface-2/70 px-3 py-2 text-xs leading-relaxed text-muted">
          This is a self-monitoring record produced by the patient&apos;s own logging app. It
          contains no diagnosis, prescription, or medical advice, and none is implied. Values
          are as entered by the patient.
        </p>
      </Card>

      <p className="text-xs text-subtle print:hidden">
        The CSV download carries the same rows with UTC + local timestamps side by side, for
        spreadsheet review.
      </p>
    </div>
  );
}

function Cell({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div>
      <dt className="text-xs font-medium uppercase tracking-wide text-subtle">{label}</dt>
      <dd className="mt-0.5 font-semibold tabular-nums">{children}</dd>
    </div>
  );
}
